const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('herta', Object.freeze({
  getConfig: () => ipcRenderer.invoke('app:config'),
  getSession: () => ipcRenderer.invoke('herta:session'),
  login: (credentials) => ipcRenderer.invoke('herta:login', credentials),
  logout: () => ipcRenderer.invoke('herta:logout'),
  platformStatus: () => ipcRenderer.invoke('platform:status'),
  startPlatform: (options) => ipcRenderer.invoke('platform:start', options),
  stopPlatform: () => ipcRenderer.invoke('platform:stop'),
  platformLogs: (service) => ipcRenderer.invoke('platform:logs', service),
  getConnectorSettings: () => ipcRenderer.invoke('connectors:settings'),
  saveConnectorSettings: (settings) => ipcRenderer.invoke('connectors:settings-save', settings),
  getTelegramStatus: () => ipcRenderer.invoke('connectors:telegram-status'),
  findTelegramChats: (botToken) => ipcRenderer.invoke('connectors:telegram-chats', botToken),
  testTelegram: () => ipcRenderer.invoke('connectors:telegram-test'),
  workerCall: (operation, payload) => ipcRenderer.invoke('platform:worker-call', operation, payload),
  listSubjects: (query) => ipcRenderer.invoke('herta:subjects', query),
  getSubjectDetails: (code) => ipcRenderer.invoke('herta:subject-detail', code),
  fetchRestSource: (config) => ipcRenderer.invoke('source:rest-fetch', config),
  testKafkaConnection: (config) => ipcRenderer.invoke('source:kafka-test', config),
  createKafkaTopic: (config, options) => ipcRenderer.invoke('source:kafka-create-topic', config, options),
  startKafkaSource: (config) => ipcRenderer.invoke('source:kafka-start', config),
  pauseKafkaSource: () => ipcRenderer.invoke('source:kafka-pause'),
  getSourceInbox: () => ipcRenderer.invoke('source:inbox'),
  loadInboxFiles: (ids) => ipcRenderer.invoke('source:inbox-load', ids),
  discardInboxItem: (id) => ipcRenderer.invoke('source:inbox-discard', id),
  startRestReceiver: (config) => ipcRenderer.invoke('source:rest-receiver-start', config),
  stopRestReceiver: () => ipcRenderer.invoke('source:rest-receiver-stop'),
  profileCheck: () => ipcRenderer.invoke('herta:profiles'),
  exportSubjects: (codes) => ipcRenderer.invoke('herta:export', codes),
  createBackup: (options) => ipcRenderer.invoke('herta:backup', options),
  getBackupSettings: () => ipcRenderer.invoke('herta:backup-settings'),
  previewBackupSchedule: (cron) => ipcRenderer.invoke('herta:backup-preview', cron),
  saveBackupSettings: (settings) => ipcRenderer.invoke('herta:backup-settings-save', settings),
  pickBackupFolder: () => ipcRenderer.invoke('files:pick-backup-folder'),
  checkHealth: () => ipcRenderer.invoke('herta:health'),
  getAuditEvents: () => ipcRenderer.invoke('herta:audit'),
  pickImportFiles: () => ipcRenderer.invoke('files:pick-import'),
  pickBackupFiles: () => ipcRenderer.invoke('files:pick-backup'),
  previewImport: (ids, group) => ipcRenderer.invoke('herta:import-preview', { ids, group }),
  importFiles: (request) => ipcRenderer.invoke('herta:import', request),
  saveReport: (report) => ipcRenderer.invoke('files:save-report', report),
}));
